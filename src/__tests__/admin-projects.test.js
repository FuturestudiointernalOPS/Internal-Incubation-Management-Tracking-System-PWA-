describe("reviewApproval", () => {
  const base = {
    projectId: "9",
    requestId: 3,
    reviewerId: "R1",
    reviewerName: "Reviewer",
    action: "approved",
    rejectionReason: undefined,
  };

  test("missing fields are a 400", async () => {
    const result = await reviewApproval({ ...base, requestId: null });
    expect(result.status).toBe(400);
  });

  test("an unknown action is a 400", async () => {
    const result = await reviewApproval({ ...base, action: "maybe" });
    expect(result.status).toBe(400);
  });

  test("rejecting without a reason is a 400", async () => {
    const result = await reviewApproval({ ...base, action: "rejected" });
    expect(result.status).toBe(400);
  });

  test("an unknown request is a 404", async () => {
    models.getProjectApprovalRequestById.mockResolvedValue({ rows: [] });
    const result = await reviewApproval(base);
    expect(result.status).toBe(404);
  });

  test("a request belonging to another project is a 404 (object-level check)", async () => {
    models.getProjectApprovalRequestById.mockResolvedValue({
      rows: [{ id: 3, project_id: "OTHER", task_id: "T1" }],
    });
    const result = await reviewApproval(base);
    expect(result.status).toBe(404);
    expect(models.updateProjectApprovalRequestStatus).not.toHaveBeenCalled();
  });

  test("approving links the task and notifies the requester", async () => {
    models.getProjectApprovalRequestById.mockResolvedValue({
      rows: [{ id: 3, project_id: "9", task_id: "T1", requester_id: "REQ" }],
    });
    const result = await reviewApproval(base);
    expect(models.updateProjectApprovalRequestStatus).toHaveBeenCalledWith(
      "approved",
      "R1",
      undefined,
      3,
    );
    expect(models.linkTaskToProject).toHaveBeenCalledWith("9", "T1");
    expect(models.createApprovalApprovedNotification).toHaveBeenCalled();
    expect(result.body.message).toContain("approved");
  });

  test("rejecting notifies the requester with the reason", async () => {
    models.getProjectApprovalRequestById.mockResolvedValue({
      rows: [{ id: 3, project_id: "9", task_id: "T1", requester_id: "REQ" }],
    });
    await reviewApproval({
      ...base,
      action: "rejected",
      rejectionReason: "not relevant",
    });
    expect(models.linkTaskToProject).not.toHaveBeenCalled();
    const [, , message] = models.createApprovalRejectedNotification.mock.calls[0];
    expect(message).toContain("not relevant");
  });

  test("an unavailable workflow answers a 200 with success false", async () => {
    models.getProjectApprovalRequestById.mockResolvedValue({
      rows: [{ id: 3, project_id: "9", task_id: "T1", requester_id: "REQ" }],
    });
    models.updateProjectApprovalRequestStatus.mockRejectedValue(new Error("no table"));
    const result = await reviewApproval(base);
    expect(result.status).toBe(200);
    expect(result.body.success).toBe(false);
  });
});

describe("generateProjectReport", () => {
  test("derives on_track, at_risk or blocked from the stats", async () => {
    models.getProjectReportTaskStats.mockResolvedValue({
      rows: [{ t: 10, c: 5, ip: 2, b: 0, co: 1 }],
    });
    await generateProjectReport(9);
    expect(models.createAutoGeneratedProjectUpdate).toHaveBeenLastCalledWith(
      9,
      expect.any(Number),
      expect.any(Number),
      expect.any(String),
      expect.any(String),
      "on_track",
    );

    models.getProjectReportTaskStats.mockResolvedValue({
      rows: [{ t: 10, c: 5, ip: 2, b: 0, co: 5 }],
    });
    await generateProjectReport(9);
    expect(models.createAutoGeneratedProjectUpdate).toHaveBeenLastCalledWith(
      9,
      expect.any(Number),
      expect.any(Number),
      expect.any(String),
      expect.any(String),
      "at_risk",
    );

    models.getProjectReportTaskStats.mockResolvedValue({
      rows: [{ t: 10, c: 5, ip: 2, b: 3, co: 0 }],
    });
    await generateProjectReport(9);
    expect(models.createAutoGeneratedProjectUpdate).toHaveBeenLastCalledWith(
      9,
      expect.any(Number),
      expect.any(Number),
      expect.any(String),
      expect.any(String),
      "blocked",
    );
  });

  test("an existing row for the week is updated in place", async () => {
    models.getProjectReportTaskStats.mockResolvedValue({
      rows: [{ t: 10, c: 5, ip: 2, b: 0, co: 0 }],
    });
    models.findProjectUpdateForReport.mockResolvedValue({ rows: [{ id: 9 }] });
    await generateProjectReport(9);
    expect(models.createAutoGeneratedProjectUpdate).not.toHaveBeenCalled();
    expect(models.updateAutoGeneratedProjectUpdate).toHaveBeenCalledWith(
      expect.any(String),
      expect.any(String),
      "on_track",
      9,
    );
  });
});
