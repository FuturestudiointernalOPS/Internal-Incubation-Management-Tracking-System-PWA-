  getAdminTaskStatsByProjectIds: jest.fn(),
  countDatedTasksByProjectIds: jest.fn(),
  getAdminBlockerStatsByProjectIds: jest.fn(),
  getAdminProjectDetails: jest.fn(),
  getTaskStatsForProject: jest.fn(),
  getTasksForProject: jest.fn(),
  getResourcesByTaskIds: jest.fn(),
  getBlockersByTaskIds: jest.fn(),
  getSubtasksByParentTaskIds: jest.fn(),
  getProjectBlockers: jest.fn(),
  getProjectMembersUnion: jest.fn(),
  getProjectTimeline: jest.fn(),
  countDatedTasksForProject: jest.fn(),
  getProjectUpdates: jest.fn(),
  findProjectUpdateId: jest.fn(),
  updateProjectUpdate: jest.fn(),
  createProjectUpdate: jest.fn(),
  getProjectApprovalRequests: jest.fn(),
  getProjectApprovalRequestById: jest.fn(),
  updateProjectApprovalRequestStatus: jest.fn(),
  linkTaskToProject: jest.fn(),
  createApprovalApprovedNotification: jest.fn(),
  createApprovalRejectedNotification: jest.fn(),
  getProjectReportTaskStats: jest.fn(),
  getRecentTasksForReport: jest.fn(),
  findProjectUpdateForReport: jest.fn(),
  updateAutoGeneratedProjectUpdate: jest.fn(),
